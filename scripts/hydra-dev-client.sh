#!/bin/sh
# Registers (or re-registers) the local development SSO client app in Hydra and
# prints environment settings for it (`make sso-client` writes them to the
# git-ignored .env.client). Development only: it deletes any existing client
# with the same ID, so the secret changes on every run.
#
# Usage: scripts/hydra-dev-client.sh [client-public-url]
#   client-public-url defaults to SSO_DEV_CLIENT_URL, else
#   http://127.0.0.1:8081. It must include a port and use a different host
#   name than the provider: cookies ignore ports.
#
# SSO_DEV_BIND, SSO_DEV_ISSUER_URL, and SSO_DEV_PROVIDER_URL (see .env.example)
# select the listen address, issuer, and provider used in the output.
#
# Hydra posts back-channel logouts to the loopback relay on 127.0.0.1:4446
# (compose service sso-backchannel-relay), which forwards to the client app:
# Hydra refuses to call Tailscale addresses directly.
set -eu

client_url="${1:-${SSO_DEV_CLIENT_URL:-http://127.0.0.1:8081}}"
client_url="${client_url%/}"
issuer_url="${SSO_DEV_ISSUER_URL:-http://127.0.0.1:4444}"
provider_url="${SSO_DEV_PROVIDER_URL:-http://localhost:8080}"
bind="${SSO_DEV_BIND:-127.0.0.1}"
client_id="${HYDRA_DEV_CLIENT_ID:-goweb-dev-client}"

# Validate before touching Hydra: the existing client is deleted below.
case "$client_url" in
http://*:[0-9]* | https://*:[0-9]*) ;;
*)
	echo "usage: $0 [client-public-url]  (for example http://127.0.0.1:8081)" >&2
	exit 2
	;;
esac
client_secret="$(od -An -tx1 -N32 /dev/urandom | tr -d ' \n')"

hydra() {
	docker compose --profile sso exec -T hydra hydra --endpoint http://127.0.0.1:4445 "$@"
}

hydra delete oauth2-client "$client_id" >/dev/null 2>&1 || true
hydra create oauth2-client \
	--id "$client_id" \
	--secret "$client_secret" \
	--name "goweb development client" \
	--grant-type authorization_code \
	--response-type code \
	--scope openid,email,profile \
	--token-endpoint-auth-method client_secret_basic \
	--redirect-uri "$client_url/en/oauth/sso/callback" \
	--post-logout-callback "$client_url/en/sign-in" \
	--backchannel-logout-callback "http://127.0.0.1:4446/oauth/sso/backchannel-logout" \
	--backchannel-logout-session-required \
	--skip-consent \
	--skip-logout-consent \
	--format json >/dev/null

client_port="${client_url##*:}"
cat <<EOF
# Development SSO client app registered with Hydra for $client_url.
# Generated by scripts/hydra-dev-client.sh; overrides .env for make run-client.
GOWEB_AUTH_MODE=client
GOWEB_HTTP_ADDR=$bind:$client_port
GOWEB_PUBLIC_URL=$client_url
GOWEB_DATABASE_URL=postgres://${POSTGRES_USER:-goweb}:${POSTGRES_PASSWORD:-goweb}@localhost:${POSTGRES_PORT:-55432}/goweb_client?sslmode=disable
GOWEB_SSO_ISSUER_URL=$issuer_url
GOWEB_SSO_CLIENT_ID=$client_id
GOWEB_SSO_CLIENT_SECRET=$client_secret
GOWEB_SSO_ACCOUNT_URL=$provider_url/en/account/settings
GOWEB_GOOGLE_CLIENT_ID=
GOWEB_GOOGLE_CLIENT_SECRET=
GOWEB_GOOGLE_REDIRECT_URL=
EOF
